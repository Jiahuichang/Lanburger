export const FONT_HEIGHT = 7;

export function textWidth(text: string): number {
  let w = 0;
  for (const ch of text.toUpperCase()) w += (G[ch] ?? G[' '])[0].length + 1;
  return Math.max(0, w - 1);
}

/** Draw uppercase text with its top-left at (x, y). Unknown characters render as spaces. */
export function drawText(c: PixelCanvas, text: string, x: number, y: number, color: string, shadow?: string): void {
  let cx = x;
  for (const ch of text.toUpperCase()) {
    const g = G[ch] ?? G[' '];
    for (let r = 0; r < g.length; r++) {
      for (let k = 0; k < g[r].length; k++) {
        if (g[r][k] !== '#') continue;
        if (shadow) c.set(cx + k, y + r + 1, shadow);
        c.set(cx + k, y + r, color);
      }
    }
    cx += g[0].length + 1;
  }
}
